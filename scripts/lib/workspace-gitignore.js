const fs = require('node:fs')
const path = require('node:path')

const MANAGED_START = '# >>> brain-corp managed >>>'
const MANAGED_END = '# <<< brain-corp managed <<<'

const DEFAULT_RULES = [
  '.brainrc.json',
  '.brain/active.json',
  '.agents/',
  '.opencode/',
  '.claude/',
  '.cursor/',
  '.antigravity/',
  '*.log',
  '.cache/',
  'tmp/',
  'dist/',
  'build/',
  '.next/'
]

function normalizeRules(rules) {
  const values = Array.isArray(rules) ? rules : DEFAULT_RULES
  return [...new Set(values.map(rule => String(rule).trim()).filter(Boolean))]
}

function managedBlock(entries, eol) {
  return [
    MANAGED_START,
    '# Generated by brain-corp. Local runtime, agent and build artifacts.',
    ...entries,
    MANAGED_END
  ].join(eol)
}

/**
 * Creates or completes a managed .gitignore block in the workspace root.
 * Existing user rules are always preserved.
 *
 * @returns {{
 *   created: boolean,
 *   updated: boolean,
 *   added: string[],
 *   path: string,
 *   entries: string[]
 * }}
 */
function ensureWorkspaceGitignore(rootDir = process.cwd(), { rules = DEFAULT_RULES } = {}) {
  const file = path.join(rootDir, '.gitignore')
  const entries = normalizeRules(rules)

  if (!fs.existsSync(file)) {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, `${managedBlock(entries, '\n')}\n`, 'utf8')

    return {
      created: true,
      updated: true,
      added: entries,
      path: file,
      entries
    }
  }

  const original = fs.readFileSync(file, 'utf8')
  const eol = original.includes('\r\n') ? '\r\n' : '\n'
  const lines = original.split(/\r?\n/)
  const startIndex = lines.findIndex(line => line.trim() === MANAGED_START)
  const endIndex =
    startIndex === -1
      ? -1
      : lines.findIndex(
          (line, index) => index > startIndex && line.trim() === MANAGED_END
        )

  if (startIndex !== -1 && endIndex !== -1) {
    const currentEntries = new Set(
      lines
        .slice(startIndex + 1, endIndex)
        .map(line => line.trim())
        .filter(line => line && !line.startsWith('#'))
    )
    const missing = entries.filter(entry => !currentEntries.has(entry))

    if (missing.length === 0) {
      return {
        created: false,
        updated: false,
        added: [],
        path: file,
        entries
      }
    }

    lines.splice(endIndex, 0, ...missing)
    fs.writeFileSync(file, lines.join(eol), 'utf8')

    return {
      created: false,
      updated: true,
      added: missing,
      path: file,
      entries
    }
  }

  const prefix = original.replace(/[\r\n\s]+$/, '')
  const next = prefix
    ? `${prefix}${eol}${eol}${managedBlock(entries, eol)}${eol}`
    : `${managedBlock(entries, eol)}${eol}`

  fs.writeFileSync(file, next, 'utf8')

  return {
    created: false,
    updated: true,
    added: entries,
    path: file,
    entries
  }
}

module.exports = {
  DEFAULT_RULES,
  MANAGED_END,
  MANAGED_START,
  ensureWorkspaceGitignore
}
